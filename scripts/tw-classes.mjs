// Writes every Tailwind class used in src/ into globals.css as `@source inline(...)`.
//
// Why: on some Windows machines an Application Control policy blocks Tailwind's
// native file scanner, and its WebAssembly fallback cannot read the disk, so
// Tailwind generates no utility classes at all. Here we read the files ourselves
// and hand their contents to the scanner, which works in both modes.
// On machines where the native scanner works this is harmless (just redundant).
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { Scanner } = require("@tailwindcss/oxide");

const ROOT = new URL("../src/", import.meta.url);
const CSS = new URL("../src/app/globals.css", import.meta.url);
const START = "/* tw-inline:start (generated by scripts/tw-classes.mjs, do not edit) */";
const END = "/* tw-inline:end */";

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if ([".ts", ".tsx"].includes(extname(p)) && !p.includes("__tests__")) out.push(p);
  }
  return out;
}

const files = walk(ROOT.pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const scanner = new Scanner({ sources: [] });
const candidates = scanner
  .scanFiles(files.map((file) => ({ content: readFileSync(file, "utf8"), extension: extname(file).slice(1) })))
  // Keep only things that can be classes and are safe inside a CSS string.
  .filter((c) => !/["'\\`\s{}]/.test(c))
  .sort();

const block = `${START}\n@source inline("${[...new Set(candidates)].join(" ")}");\n${END}`;
const css = readFileSync(CSS, "utf8");
const next = css.includes(START)
  ? css.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&")}`), block)
  : css.replace(/(@import "tailwindcss"[^;]*;)/, `$1\n${block}`);

if (next !== css) writeFileSync(CSS, next);
console.log(`tw-classes: ${candidates.length} candidates from ${files.length} files`);
