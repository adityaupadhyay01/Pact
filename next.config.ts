import type { NextConfig } from "next";

/**
 * Security headers for every response.
 * - Referrer-Policy: sessions are bearer links (?session=…); never leak them to PayPal, fonts or other sites.
 * - frame-ancestors / X-Frame-Options: no clickjacking of the approve and pay buttons.
 * A full script CSP is not set: the PayPal JS SDK loads scripts and frames from several PayPal domains.
 */
const securityHeaders = [
  { key: "Referrer-Policy", value: "no-referrer" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'; object-src 'none'; base-uri 'self'; form-action 'self'" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
